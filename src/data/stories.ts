export interface StoryToken {
  surface: string;
  reading?: string;
  meaning?: string;
  baseForm?: string;
  level?: string;
}

export interface StoryParagraph {
  ja: string;      // Japanese sentence/paragraph
  en: string;      // English translation
  tokens?: {       // Optional pre-parsed tokens for ruby
    surface: string;
    reading?: string;
    meaning?: string;
    baseForm?: string;
    level?: string;
  }[];
}

export interface StoryQuiz {
  question: string;
  options: string[];
  answerIndex: number;
}

